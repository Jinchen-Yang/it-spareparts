def make_rows(*, orders: int = 2, lines_per_order: int = 2,
              headless: int = 0, project: str = "合成项目A") -> list[dict]:
    """生成 orders 个有明细订单（每单 lines_per_order 行）+ headless 个无明细单头行。"""
    rows: list[dict] = []
    for o in range(1, orders + 1):
        oid, ono = f"SYN-O{o:03d}", f"WBDD-2026{o:04d}"
        for ln in range(1, lines_per_order + 1):
            row = {**_base_head(oid, ono, project=project),
                   **_base_line(f"SYN-L{o:03d}-{ln}", ln, pn=f"PN-SYN-{o:03d}{ln}")}
            rows.append(row)
    for h in range(1, headless + 1):
        oid, ono = f"SYN-H{h:03d}", f"WBDD-2026H{h:03d}"
        rows.append(_base_head(oid, ono, project=project))  # 无任何明细字段
    return rows


def write_workbook(path: str, columns: list[str], rows: list[dict]) -> str:
    """写双表头 .xlsx：F 码行 + 业务名行 + 数据行。"""
    wb = Workbook()
    ws = wb.active
    ws.title = "维保备件需求单"
    ws.append([f"F{i:07d}" for i in range(len(columns))])   # 第 0 行：F 字段码
    ws.append(columns)                                       # 第 1 行：业务名
    for row in rows:
        ws.append([row.get(c, "") for c in columns])
    wb.save(path)
    return path
